r_start=0.096;
m1=0.192*2;
m2=0.32*2;
x=zeros(300);
L=zeros(300);
LM=zeros(300);
I=zeros(300);
for i=1:300
    r_start=r_start+0.001;
    leg_var=r_start;
    xie=sqrt(r_start^2+0.075^2);
    theta1=asin(0.075/xie);
    theta2=acos((xie^2+0.27^2-0.15^2)/(2*xie*0.27));
    thetatotal=theta1+theta2;
    x(i)=r_start;
    L(i) =(0.32*0.108*cos(thetatotal)+0.192*(0.27*cos(thetatotal)+0.052/0.15*(leg_var-0.27*cos(thetatotal))))/(0.32+0.192);
    LM(i)=r_start-L(i);
    % xie1=sqrt(leg_var^2+0.27^2-2*cos(thetatotal)*0.27*leg_var);
    % xie2=sqrt(0.108/0.27*xie1^2+(0.27-0.108)/0.27*leg_var^2-0.108*(0.27-0.108));
    % xie3=sqrt(0.052/0.15*0.075^2+0.098/0.15*xie1^2-0.052*0.098);
    % I(i)=m1*xie3^2+m2*xie2^2+1/3*m2*0.27^2+1/3*m1*0.15^2+(m1+m2)*LM(i)^2;
    xie1=sqrt(L(i)^2+0.27^2-2*cos(thetatotal)*0.27*L(i));
    xie2=sqrt(0.075^2+LM(i)^2);
    xie3=sqrt(0.108/0.27*xie1^2+(0.27-0.108)/0.27*L(i)^2-0.108*(0.27-0.108));
    xie4=sqrt(0.052/0.15*xie2^2+0.098/0.15*xie1^2-0.052*0.098);
    I(i)=m1*xie3^2+m2*xie4^2+1/3*m2*0.27^2+1/3*m1*0.15^2;
end
plot(x,L);
hold on;
